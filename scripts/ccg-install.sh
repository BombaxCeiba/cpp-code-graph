#!/bin/sh
# ccg PATH installer (POSIX variant). The contract in short: two
# forwarding shims into a bin directory plus one guarded PATH line in
# ~/.bashrc, idempotent, and nothing outside the bin directory and that
# rc line is touched (fuller statement in the sections below).
#
# Definition: writes two forwarding shims into a bin directory - an
# extensionless `ccg` (what POSIX shells resolve first) and ccg.cmd (for
# cmd.exe/PowerShell hosts sharing the same bin directory, Git Bash
# setups) - each forwarding to the release binary by absolute path, then
# adds the bin directory to PATH through one guarded line appended to
# ~/.bashrc.
#
# Soundness boundary: nothing outside the bin directory and that one
# guarded rc line is touched; the release directory is never modified;
# the CURRENT shell's PATH is never edited (the rc line lands in new
# shells). Idempotent: re-running refreshes the shims; the rc append is
# guarded by a literal line match and never duplicates.
#
# Fallbacks: CCG_BIN pointing at the binary stays honored by the hook
# trampolines before any PATH lookup; the release directory itself can
# be added to PATH by hand - those two are the manual shapes.
#
# usage: ccg-install.sh [release-dir] [--bin DIR] [--no-path]
#   release-dir  directory holding ccg/ccg.exe + .ccg + docs
#                (default: this script's own directory)
#   --bin DIR    where the shims go (default: ~/.local/bin)
#   --no-path    write the shims but leave PATH untouched
set -eu

usage() {
    echo "usage: ccg-install.sh [release-dir] [--bin DIR] [--no-path]" >&2
}

release=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
bin_dir=${HOME:-.}/.local/bin
add_path=1

while [ $# -gt 0 ]; do
    case $1 in
    --bin)
        [ $# -ge 2 ] || { usage; exit 1; }
        bin_dir=$2
        shift 2
        ;;
    --no-path)
        add_path=0
        shift
        ;;
    -h|--help)
        usage
        exit 0
        ;;
    -*)
        usage
        exit 1
        ;;
    *)
        release=$1
        shift
        ;;
    esac
done
release=$(CDPATH= cd -- "$release" 2>/dev/null && pwd) || {
    echo "ccg-install: cannot enter release directory '$release'" >&2
    exit 1
}

ccg_bin=
for cand in "$release/ccg" "$release/ccg.exe"; do
    if [ -x "$cand" ]; then
        ccg_bin=$cand
        break
    fi
done
if [ -z "$ccg_bin" ]; then
    echo "ccg-install: no ccg binary in '$release'" >&2
    echo "ccg-install: pass the release directory (cmake --install output) as the first argument" >&2
    exit 1
fi

mkdir -p "$bin_dir"

# POSIX shim: LF endings are native here.
{
    echo '#!/bin/sh'
    printf 'exec "%s" "$@"\n' "$ccg_bin"
} > "$bin_dir/ccg"
chmod 755 "$bin_dir/ccg"

# cmd shim for hosts that share this bin directory: cmd.exe requires CRLF
# endings (and the paths must use forward slashes - the ones from pwd
# already do), so both lines are emitted with an explicit \r.
{
    printf '@rem ccg shim generated by ccg-install.sh - forwards to the release binary\r\n'
    printf '@"%s" %%*\r\n' "$ccg_bin"
} > "$bin_dir/ccg.cmd"

if [ "$add_path" = 1 ]; then
    case ":$PATH:" in
    *":$bin_dir:"*)
        echo "ccg-install: $bin_dir already on PATH"
        ;;
    *)
        rc=${HOME:-.}/.bashrc
        line="export PATH=\"\$PATH:$bin_dir\""
        if grep -qsF "$line" "$rc"; then
            echo "ccg-install: $rc already exports $bin_dir"
        else
            printf '\n# added by ccg-install.sh - ccg shims on PATH\n%s\n' \
                "$line" >> "$rc"
            echo "ccg-install: appended $bin_dir to $rc"
        fi
        ;;
    esac
fi

echo "ccg-install: binary    $ccg_bin"
echo "ccg-install: shim      $bin_dir/ccg"
echo "ccg-install: shim      $bin_dir/ccg.cmd (cmd)"
echo "ccg-install: docs      $release/docs"
echo "ccg-install: open a NEW shell (PATH edits never touch the current one), then: ccg --version"
echo "ccg-install: Claude Code integration: ccg hook install --project (run in your project root)"
